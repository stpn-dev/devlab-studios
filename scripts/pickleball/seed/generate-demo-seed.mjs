// --- Helpers to derive teams/games/stats from a plain description --------

let teamSeq = 0
let gameSeq = 0
let scoreEventSeq = 0
let gameParticipantSeq = 0
let playerGameStatSeq = 0

// One row per (playerId, scopeType, scopeId) accumulator, built up as games
// are processed below -- mirrors buildRecomputePlayerSnapshotsStatements's
// SUM/COUNT aggregation (playerPerformanceSnapshots.js), just computed once
// here instead of via SQL aggregate functions.
const snapshotAccumulators = new Map()

function accumulateSnapshot(playerId, scopeType, scopeId, gamePerformance) {
  const key = `${playerId}::${scopeType}::${scopeId}`
  const existing = snapshotAccumulators.get(key) || { playerId, scopeType, scopeId, eligibleGamesCount: 0, performanceSum: 0 }
  existing.eligibleGamesCount += 1
  existing.performanceSum += gamePerformance
  snapshotAccumulators.set(key, existing)
}

// Builds one finished DOUBLES game: two AD_HOC teams, their members, the
// game row itself (status FINISHED from creation), a minimal two-event
// score_events pair (GAME_STARTED/GAME_FINISHED -- sufficient for a static,
// already-finished seed row; nothing ever undoes/reopens/replays seed data),
// game_participants, and player_game_stats for all four participants. Feeds
// both the game's own session's SESSION-scope snapshot accumulator and the
// shared ALL_TIME accumulator for each participant.
function addFinishedGame({ sessionId, sessionCourtId, teamAPlayerIndexes, teamBPlayerIndexes, scoreA, scoreB, startedAt, finishedAt }) {
  teamSeq += 1
  const teamAId = `seed-team-a-${teamSeq}`
  teamSeq += 1
  const teamBId = `seed-team-b-${teamSeq}`
  gameSeq += 1
  const gameId = `seed-game-${gameSeq}`
  const winningTeamId = scoreA > scoreB ? teamAId : teamBId

  statements.push(insert('teams', { id: teamAId, session_id: sessionId, kind: 'AD_HOC', created_at: startedAt }))
  statements.push(insert('teams', { id: teamBId, session_id: sessionId, kind: 'AD_HOC', created_at: startedAt }))

  const teamMembers = [
    ...teamAPlayerIndexes.map((playerIndex) => ({ teamId: teamAId, playerIndex })),
    ...teamBPlayerIndexes.map((playerIndex) => ({ teamId: teamBId, playerIndex })),
  ]
  teamMembers.forEach(({ teamId, playerIndex }) => {
    statements.push(insert('team_members', {
      id: `seed-tm-${teamId}-${playerIndex}`, team_id: teamId, session_player_id: liveSessionPlayerId(playerIndex),
    }))
  })

  statements.push(insert('games', {
    id: gameId, session_id: sessionId, session_court_id: sessionCourtId, scoring_ruleset_id: GLOBAL_RULESET_ID,
    format: 'DOUBLES', status: 'FINISHED', team_a_id: teamAId, team_b_id: teamBId, revision: 2,
    score_a: scoreA, score_b: scoreB, serving_team: 'A', server_number: 1, winning_team_id: winningTeamId,
    final_score_a: scoreA, final_score_b: scoreB, started_at: startedAt, finished_at: finishedAt,
    created_at: startedAt, updated_at: finishedAt,
  }))

  scoreEventSeq += 1
  statements.push(insert('score_events', {
    id: `seed-event-${scoreEventSeq}`, game_id: gameId, sequence: 1, event_type: 'GAME_STARTED',
    actor_user_id: 'seed-script', payload_json: JSON.stringify({ scoreA: 0, scoreB: 0, servingTeam: 'A', serverNumber: 2 }),
    created_at: startedAt,
  }))
  scoreEventSeq += 1
  statements.push(insert('score_events', {
    id: `seed-event-${scoreEventSeq}`, game_id: gameId, sequence: 2, event_type: 'GAME_FINISHED',
    actor_user_id: 'seed-script', payload_json: JSON.stringify({ scoreA, scoreB, winningTeamId }),
    created_at: finishedAt,
  }))

  teamMembers.forEach(({ teamId, playerIndex }) => {
    const player = players[playerIndex]
    const onTeamA = teamId === teamAId
    const pointsFor = onTeamA ? scoreA : scoreB
    const pointsAgainst = onTeamA ? scoreB : scoreA
    // Spec §8's exact formula -- see this file's header comment for why it's
    // duplicated here rather than imported.
    const gamePerformance = (pointsFor / (pointsFor + pointsAgainst)) * 100

    gameParticipantSeq += 1
    statements.push(insert('game_participants', {
      id: `seed-gp-${gameParticipantSeq}`, game_id: gameId, session_player_id: liveSessionPlayerId(playerIndex), team_id: teamId,
    }))

    playerGameStatSeq += 1
    statements.push(insert('player_game_stats', {
      id: `seed-pgs-${playerGameStatSeq}`, game_id: gameId, player_id: player.id,
      points_for: pointsFor, points_against: pointsAgainst, game_performance: gamePerformance,
      is_win: winningTeamId === teamId ? 1 : 0, eligible_for_opi: 1, created_at: finishedAt,
    }))

    accumulateSnapshot(player.id, 'SESSION', sessionId, gamePerformance)
    accumulateSnapshot(player.id, 'ALL_TIME', 'ALL_TIME', gamePerformance)
  })
}

